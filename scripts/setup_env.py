"""`make setup` helper: create .env and the workspace folder. Safe to run again.

- copies .env.example to .env if there's no .env yet
- sets HOST_WORKSPACE (the workspace's absolute path on this machine), which the
  dockerised API needs to mount files into sandbox containers
- generates random secrets for the self-hosted Langfuse stack (never shipped defaults)
- creates workspace/ and adds the example data the first time

Existing values in .env are never changed.
"""

import secrets
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generated_values(workspace: Path) -> dict[str, str]:
    return {
        # Forward slashes work for Docker on Windows, macOS and Linux.
        "HOST_WORKSPACE": workspace.as_posix(),
        # Langfuse (observability profile): server secrets, project API keys, UI login.
        "LANGFUSE_NEXTAUTH_SECRET": secrets.token_hex(32),
        "LANGFUSE_SALT": secrets.token_hex(16),
        "LANGFUSE_ENCRYPTION_KEY": secrets.token_hex(32),  # must be 64 hex chars
        "LANGFUSE_DB_PASSWORD": secrets.token_hex(16),
        "LANGFUSE_PUBLIC_KEY": f"pk-lf-{secrets.token_hex(12)}",
        "LANGFUSE_SECRET_KEY": f"sk-lf-{secrets.token_hex(16)}",
        "LANGFUSE_UI_PASSWORD": secrets.token_urlsafe(12),
    }


def main() -> None:
    env = ROOT / ".env"
    if not env.exists():
        shutil.copy(ROOT / ".env.example", env)
        print("created .env from .env.example")

    workspace = ROOT / "workspace"
    lines = env.read_text(encoding="utf-8").splitlines()
    present = {
        line.split("=", 1)[0].strip() for line in lines if "=" in line and not line.startswith("#")
    }
    added = {k: v for k, v in generated_values(workspace).items() if k not in present}
    if added:
        lines += ["", "# --- generated by `make setup` ---"] + [
            f"{k}={v}" for k, v in added.items()
        ]
        env.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("added to .env: " + ", ".join(added))

    if not workspace.exists():
        workspace.mkdir()
        for example in (ROOT / "examples").iterdir():
            shutil.copy(example, workspace / example.name)
        print("created workspace/ with the example files")


if __name__ == "__main__":
    main()
